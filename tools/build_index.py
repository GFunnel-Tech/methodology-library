#!/usr/bin/env python3
"""Build departments/<dept>/README.md from the front matter of every algorithm and pattern.

Run: python3 tools/build_index.py          (write)
     python3 tools/build_index.py --check  (exit 1 if an index is stale or a header is bad)
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
meta = json.loads((ROOT / "methodology.json").read_text())
DEPTS = meta["departments"]
TITLES = {"hr": "HR & Culture", "client_success": "Client Success"}
prefixes = {p["prefix"]: p["slug"] for p in meta["people"]}
errors, rows = [], {d: [] for d in DEPTS}

for f in sorted(ROOT.glob("people/*/[ap][la]*/*.md")):
    text = f.read_text()
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        errors.append(f"{f}: no header"); continue
    h = dict(re.findall(r"^(\w+):\s*(.*)$", m.group(1), re.M))
    depts = [d.strip() for d in h.get("departments", "").strip("[]").split(",") if d.strip()]
    pid = h.get("id", "")
    if prefixes.get(pid.split("-")[0]) != h.get("person"):
        errors.append(f"{f}: id prefix does not match person")
    if h.get("source") not in ("stated", "derived"):
        errors.append(f"{f}: source must be stated or derived")
    title = re.search(r"^# (.+)$", text[m.end():], re.M)
    for d in depts:
        if d not in rows:
            errors.append(f"{f}: unknown department {d}"); continue
        rows[d].append((pid, title.group(1) if title else f.stem, h.get("person"), h.get("source"),
                        f.relative_to(ROOT).as_posix()))

check = "--check" in sys.argv
stale = []
for d in DEPTS:
    out = [f"# {TITLES.get(d, d.title())} — methods by person", "",
           "Generated by `tools/build_index.py` — do not edit by hand.", ""]
    if rows[d]:
        out += ["| ID | Method | Person | Source |", "| --- | --- | --- | --- |"]
        out += [f"| {i} | [{t}](../../{p}) | {who} | {s} |" for i, t, who, s, p in rows[d]]
    else:
        out += ["Nothing researched for this department yet."]
    body = "\n".join(out) + "\n"
    path = ROOT / "departments" / d / "README.md"
    if check:
        if not path.exists() or path.read_text() != body: stale.append(d)
    else:
        path.parent.mkdir(parents=True, exist_ok=True); path.write_text(body)

for e in errors: print("ERROR", e)
for d in stale: print("STALE", d)
sys.exit(1 if errors or stale else 0)
