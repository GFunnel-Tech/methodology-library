#!/usr/bin/env python3
"""Build every domain's facet indexes (e.g. domains/business/departments/<dept>/README.md)
from the header of each algorithm and pattern, and check the library is consistent.

Run: python3 tools/build_index.py          (write)
     python3 tools/build_index.py --check  (exit 1 if an index is stale or anything is inconsistent)
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
lib = json.loads((ROOT / "library.json").read_text())
TITLES = {"hr": "HR & Culture", "client_success": "Client Success"}
check, errors, stale, seen = "--check" in sys.argv, [], [], {}

for dom in lib["domains"]:
    dpath = ROOT / dom["path"]
    meta = json.loads((dpath / "domain.json").read_text())
    facet, values = meta["facet"]["name"], meta["facet"]["values"]
    rows = {v: [] for v in values}
    for p in meta["people"]:
        owner = lib["prefixes"].get(p["prefix"])
        if owner != f'{dom["slug"]}/{p["slug"]}':
            errors.append(f'prefix {p["prefix"]} not registered to {dom["slug"]}/{p["slug"]} in library.json')
        if not (dpath / p["path"] / "methodology.json").exists():
            errors.append(f'{dom["slug"]}/{p["slug"]}: missing methodology.json')
    prefixes = {p["prefix"]: p["slug"] for p in meta["people"]}
    for f in sorted(dpath.glob("people/*/algorithms/*.md")) + sorted(dpath.glob("people/*/patterns/*.md")):
        rel = f.relative_to(ROOT).as_posix()
        text = f.read_text()
        m = re.match(r"---\n(.*?)\n---\n", text, re.S)
        if not m:
            errors.append(f"{rel}: no header"); continue
        h = dict(re.findall(r"^(\w+):\s*(.*)$", m.group(1), re.M))
        pid = h.get("id", "")
        if pid in seen: errors.append(f"{rel}: id {pid} already used by {seen[pid]}")
        seen[pid] = rel
        if prefixes.get(pid.split("-")[0]) != h.get("person"):
            errors.append(f"{rel}: id prefix does not match person")
        if h.get("source") not in ("stated", "derived"):
            errors.append(f"{rel}: source must be stated or derived")
        title = re.search(r"^# (.+)$", text[m.end():], re.M)
        for v in [x.strip() for x in h.get(facet, "").strip("[]").split(",") if x.strip()]:
            if v not in rows: errors.append(f"{rel}: unknown {facet} '{v}'"); continue
            rows[v].append((pid, title.group(1) if title else f.stem, h.get("person"), h.get("source"),
                            f.relative_to(dpath).as_posix()))
    for v in values:
        out = [f"# {TITLES.get(v, v.replace('_', ' ').title())} — methods by person", "",
               "Generated by `tools/build_index.py` — do not edit by hand.", ""]
        if rows[v]:
            out += ["| ID | Method | Person | Source |", "| --- | --- | --- | --- |"]
            out += [f"| {i} | [{t}](../../{p}) | {who} | {s} |" for i, t, who, s, p in rows[v]]
        else:
            out += ["Nothing researched here yet."]
        body, path = "\n".join(out) + "\n", dpath / facet / v / "README.md"
        if check:
            if not path.exists() or path.read_text() != body: stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_text(body)

for e in errors: print("ERROR", e)
for s in stale: print("STALE", s)
sys.exit(1 if errors or stale else 0)
